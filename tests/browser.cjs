/* Optional integration test: needs Playwright and installed Chrome/Edge. */
const { chromium } = require(process.argv[2] || process.env.OSINT_PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');

(async()=>{
  const browser=await chromium.launch({channel:process.env.OSINT_TEST_BROWSER || 'msedge',headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
  const page=await context.newPage(), errors=[], external=[], failedRequests=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
  page.on('requestfailed',request=>failedRequests.push({url:request.url(),error:request.failure()?.errorText}));
  await context.route('**/*',route=>{const host=new URL(route.request().url()).hostname;if(host==='127.0.0.1')return route.continue();external.push(host);return route.abort();});
  const base=process.env.OSINT_TEST_URL || 'http://127.0.0.1:8765/';
    const dir=path.resolve('tmp/browser-test');await fs.mkdir(dir,{recursive:true});
  const go=async hash=>{await page.evaluate(value=>{location.hash=value;},hash);await page.waitForTimeout(80);};
  const visible=async selector=>{await page.locator(selector).waitFor({state:'visible',timeout:6000});};
  try{
    await page.goto(base,{waitUntil:'networkidle'});
    await visible('main h1');
    assert.match(await page.locator('main h1').innerText(),/Пространство/);
    assert.equal(await page.locator('.chapter-card').count(),6);
    await page.screenshot({path:path.join(dir,'desktop.png'),fullPage:true});
    await go('course');assert.equal(await page.locator('.chapter-card').count(),10);
    await go('lesson/L01');await page.getByRole('button',{name:'Отметить пройденным',exact:true}).click();
    await page.reload();await visible('[data-action="lesson-complete"]');
    assert.match(await page.locator('[data-action="lesson-complete"]').innerText(),/пройден/);
    await go('case/C01');await page.locator('[data-doc="materials"]').click();await visible('#document-dialog[open]');
    assert.match(await page.locator('#document-body').innerText(),/D07/);
    await page.locator('[data-close-dialog]').click();
    const answer='Версии нужно проверить по D01 и D02. Дата анонса не равна дате события.';
    await page.locator('#case-answer').fill(answer);await page.reload();await visible('#case-answer');
    assert.equal(await page.locator('#case-answer').inputValue(),answer);
    await page.locator('[data-action="case-complete"]').click();
    await page.locator('[data-action="new-report"]').click();await visible('#report-editor');
    await page.locator('#report-title').fill('Учебный <img src=x onerror=alert(1)> отчёт');
    await page.locator('#report-question').fill('В какую дату состоялось публичное открытие?');
    await page.locator('#report-findings').fill('О переносе говорит D02. Независимость источников требует отдельной оценки.');
    await page.locator('[data-action="add-source"]').click();
    await page.locator('#source-0-title').fill('Уведомление об изменении программы');
    await page.locator('#source-0-url').fill('D02');
    await page.locator('#source-0-published').fill('2025-09-11');
    const downloadPromise=page.waitForEvent('download');await page.locator('[data-action="export-report"]').click();
    const download=await downloadPromise, exported=await fs.readFile(await download.path(),'utf8');
    assert.ok(exported.includes('2025-09-11'));assert.ok(exported.includes('В какую дату'));
    await page.getByRole('link',{name:'Просмотр и печать',exact:true}).click();
    await visible('main .prose');assert.equal(await page.locator('main .prose img').count(),0);
    assert.match(await page.locator('main .prose').innerText(),/<img src=x/);
    await go('reports');
    assert.equal(await page.locator('.report-card').count(),1);
    const backupPromise=page.waitForEvent('download');await page.locator('[data-action="backup"]').click();
    const backup=await backupPromise, backupBytes=await fs.readFile(await backup.path());
    const before=await page.evaluate(()=>localStorage.getItem('osint-practice-v1'));
    await page.locator('#backup-file').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{"format":"other"}')});
    await page.waitForTimeout(120);assert.equal(await page.evaluate(()=>localStorage.getItem('osint-practice-v1')),before);
    page.once('dialog',dialog=>dialog.accept());
    await page.locator('#backup-file').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:backupBytes});
    await page.waitForTimeout(120);assert.equal(await page.locator('.report-card').count(),1);
    await go('tools');await page.locator('#list-query').fill('ExifTool');
    assert.equal(await page.locator('.tool-card').count(),1);
    await page.locator('[data-action="favorite"]').click();
    await page.locator('#list-query').fill('');await page.locator('[data-action="favorites-filter"]').click();
    assert.equal(await page.locator('.tool-card').count(),1);
    await go('helpers');await page.locator('#coordinates-form button').click();
    assert.match(await page.locator('#coordinate-result').innerText(),/55° 45/);
    await page.locator('#latitude').fill('91');await page.locator('#coordinates-form button').click();
    assert.match(await page.locator('#coordinate-result').innerText(),/пределах/);
    await page.locator('#hash-file').setInputFiles({name:'abc.txt',mimeType:'text/plain',buffer:Buffer.from('abc')});
    await page.waitForFunction(()=>document.getElementById('hash-result').textContent.includes('ba7816bf8f01cfea'));
    await context.setOffline(true);await go('lesson/L22');assert.match(await page.locator('main h1').innerText(),/интервью/);await context.setOffline(false);
    await page.locator('#global-query').fill('первоисточник');await page.locator('#global-search').evaluate(form=>form.requestSubmit());
    await page.waitForTimeout(120);assert.ok(await page.locator('.search-result').count()>0);
    await page.setViewportSize({width:390,height:844});await go('home');
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Mobile page should not overflow');
    await page.waitForFunction(()=>document.getElementById('toast').hidden);
    await page.screenshot({path:path.join(dir,'mobile.png'),fullPage:true});
    await go('case/C19');assert.equal(await page.locator('#case-answer').count(),0);assert.match(await page.locator('.notice.warning').innerText(),/не подготовлены/);
    if(errors.length)console.log('Failed requests:',JSON.stringify(failedRequests));
    assert.deepEqual(errors,[],'Browser errors');assert.deepEqual(external,[],'No external requests before user opens external links');
    console.log('Browser check passed: navigation, progress, case documents, drafts, reports, safe rendering, export/import, tools, coordinates, hash, offline lessons and mobile layout.');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
